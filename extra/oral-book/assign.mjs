/* ---------- 自检 ---------- */
export function validate(total = 496) {
  const hit = new Array(total).fill(null);
  const errs = [];
  for (const [deck, ranges] of Object.entries(ASSIGN)) {
    ranges.forEach(([a, b]) => {
      for (let i = a; i <= b; i++) {
        if (i < 0 || i >= total) { errs.push(`索引越界 ${deck} ${i}`); continue; }
        if (hit[i]) errs.push(`重复归入 ${i}：${hit[i]} 与 ${deck}`);
        hit[i] = deck;
      }
    });
  }
  hit.forEach((d, i) => { if (!d) errs.push(`未归入 ${i}`); });
  return { errs, hit };
}

if (process.argv[1] && process.argv[1].endsWith('exist-assign-fixed.mjs')) {
  const { errs, hit } = validate();
  const byDeck = {};
  hit.forEach((d) => { if (d) byDeck[d] = (byDeck[d] || 0) + 1; });
  console.log('归入 deck 数:', Object.keys(byDeck).length);
  console.log('覆盖:', hit.filter(Boolean).length, '/ 496');
  if (errs.length) { console.log('❌ 问题 ' + errs.length + ':'); errs.slice(0, 20).forEach((e) => console.log('   ' + e)); process.exitCode = 1; }
  else console.log('✓ 无重复、无遗漏');
  Object.entries(byDeck).sort((a, b) => b[1] - a[1]).forEach(([d, n]) => console.log('  ' + String(n).padStart(3) + '  ' + d));
}
