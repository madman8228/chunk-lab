import esbuild from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
export async function buildMembership({
  serverOut = path.join(root, 'server/services/membership/policies.cjs'),
  browserOut = path.join(root, 'js/membership.js')
} = {}) {
  await Promise.all([
    esbuild.build({ entryPoints: [path.join(root, 'scripts/membership-publication-entry.mjs')], outfile: path.join(path.dirname(serverOut), 'publication-compiler.cjs'),
      bundle: true, format: 'cjs', platform: 'node', target: 'node18', minify: true, legalComments: 'none',
      banner: { js: '// @ts-nocheck\n// Generated by build-membership.mjs; source is checked in membership-publication-entry.mjs.' } }),
    esbuild.build({ entryPoints: [path.join(root, 'scripts/membership-policies-entry.mjs')], outfile: serverOut,
      bundle: true, format: 'cjs', platform: 'node', target: 'node18', minify: false, legalComments: 'none' }),
    esbuild.build({ entryPoints: [path.join(root, 'scripts/membership-browser-entry.mjs')], outfile: browserOut,
      bundle: true, format: 'iife', platform: 'browser', globalName: 'ChunkMembership', minify: false, legalComments: 'none' })
  ]);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildMembership();
