import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function loadWindow(file, window = {}) {
  vm.runInNewContext(fs.readFileSync(path.join(root, file), 'utf8'), { window, console }, { filename: file });
  return window;
}

function normalizedSentence(sentence) {
  return String(sentence || '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

const oralDecks = loadWindow('oral-book.js').ORAL_BOOK.decks;
const oral = oralDecks.flatMap((deck) => deck.items);
const legacyBuiltin = loadWindow('extra/oral-book/base/builtins.js').BUILTIN || [];
const legacyOral = loadWindow('extra/oral-book/base/oral8000.js', { BUILTIN: { push() {}, concat() { return []; } } }).DATA_ORAL8000 || [];
const legacyBySentence = new Map([...legacyBuiltin.flatMap((deck) => deck.items || []), ...legacyOral]
  .map((item) => [normalizedSentence(item.sentence), item]));
let legacyIdsChecked = 0;
for (const item of oral) {
  const legacy = legacyBySentence.get(normalizedSentence(item.sentence));
  if (!legacy) continue;
  assert.equal(item.cid, legacy.cid, `${item.sentence}: content overlay changed the legacy cid`);
  legacyIdsChecked++;
}
assert.equal(legacyIdsChecked, 496, 'all 496 legacy sentence IDs must remain stable');
const freqWindow = loadWindow('freq-idioms.js', { BUILTIN: [] });
const freq = freqWindow.BUILTIN.find((deck) => deck.id === 'builtin-freq-idioms').items;
const freqBySentence = new Map(freq.map((item) => [item.sentence, item]));
const allItems = [...oral, ...freq];

for (const [index, item] of allItems.entries()) {
  assert.ok(Array.isArray(item.chunks) && item.chunks.length > 0, `item ${index}: chunks missing`);
  assert.ok(Array.isArray(item.hints), `item ${index}: hints missing`);
  assert.equal(item.hints.length, item.chunks.length, `${item.sentence}: chunk/hint count differs`);
  assert.ok(item.hints.every((hint) => typeof hint === 'string' && hint.trim()), `${item.sentence}: empty hint`);
}

