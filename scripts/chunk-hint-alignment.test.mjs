const deicticCues = [
  [/\b(?:this|these)\b/i, /这|此|本|这些|这个|这里|此事/],
  [/\b(?:that|those)\b/i, /那|那些|那个|那里|那种|那就/],
  [/\bhere\b/i, /这儿|这里|此处/],
  [/\bthere\b/i, /那里|那儿/],
];
const reviewedDeicticCandidates = new Set([
  "That's right.", // Chinese naturally assigns “那样” to the second chunk.
  'We understand from Mr. Aoki that...', // “that” introduces the following clause.
]);
const deicticCrossovers = new Set();
for (const item of allItems) {
  for (let index = 0; index < item.chunks.length; index += 1) {
    for (const [englishCue, chineseCue] of deicticCues) {
      if (!englishCue.test(item.chunks[index]) || chineseCue.test(item.hints[index])) continue;
      if (item.hints.some((hint, otherIndex) => otherIndex !== index && chineseCue.test(hint))) {
        deicticCrossovers.add(item.sentence);
      }
    }
  }
}
assert.deepEqual(
  [...deicticCrossovers].sort(),
  [...reviewedDeicticCandidates].sort(),
  'new demonstrative/location cue and hint crossover needs semantic review',
);

