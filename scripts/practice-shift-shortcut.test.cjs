'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('main.html','utf8'),keys={},win={},actions=[];
const snippet=html.slice(html.indexOf('function switchToSpelling(){'),html.indexOf("$('stageTipBar').addEventListener('click'"));
const sandbox={_curPage:'pagePractice',S:{finished:false,assessment:null,answers:[],status:[]},cur:()=>({}),effectivePracticeMode:()=>sandbox.S.spellingOverride===true?'type':sandbox.S.spellingOverride||'choose',inputsAt:()=>[],renderQ:preserve=>actions.push(preserve),document:{querySelector:()=>null,addEventListener:(key,fn)=>{keys[key]=fn;}},window:{addEventListener:(key,fn)=>{win[key]=fn;}}};
vm.runInNewContext(snippet,sandbox);
keys.keydown({key:'Shift'});keys.keyup({key:'Shift'});
assert.equal(sandbox.effectivePracticeMode(),'type');assert.deepEqual(actions,[true]);
keys.keydown({key:'Shift'});keys.keyup({key:'Shift'});
assert.equal(sandbox.effectivePracticeMode(),'choose','second Shift returns to selection');
keys.keydown({key:'Shift'});keys.keyup({key:'Shift'});
assert.equal(sandbox.effectivePracticeMode(),'type','third Shift returns to spelling');
actions.length=1;
sandbox.S.spellingOverride=false;keys.keydown({key:'Shift'});keys.keydown({key:'A',shiftKey:true});keys.keyup({key:'Shift'});assert.equal(sandbox.S.spellingOverride,false,'Shift+letter is not a mode switch');
keys.keydown({key:'Shift',ctrlKey:true});keys.keyup({key:'Shift',ctrlKey:true});assert.equal(actions.length,1);
keys.keydown({key:'Shift'});win.blur();keys.keyup({key:'Shift'});assert.equal(actions.length,1);
sandbox.S.assessment={};keys.keydown({key:'Shift'});keys.keyup({key:'Shift'});assert.equal(actions.length,1,'assessment is not modified');
assert.ok(html.indexOf('data-action="spelling"')<html.indexOf('data-action="hint"'),'Shift hint appears before Ctrl+M');
console.log('Shift spelling shortcut: solo key, combinations, blur, assessment guards and hint order passed.');
