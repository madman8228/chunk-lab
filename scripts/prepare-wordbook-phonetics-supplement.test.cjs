'use strict';
const assert=require('node:assert/strict');
const {transcribe,dictionary}=require('./prepare-wordbook-phonetics-supplement.cjs');
const us=dictionary(Buffer.from("read\t/ˈrɛd/, /ˈrid/\nlead\t/ˈlɛd/, /ˈlid/\nturn\t/ˈtɝn/\nright\t/ˈraɪt/\nleft\t/ˈlɛft/\nused\t/ˈjuzd/\nto\t/ˈtu/\nfirst\t/ˈfɝst/\nfather\t/ˈfɑðɝ/\ndad\t/ˈdæd/\nmake\t/ˈmeɪk/\nuse\t/ˈjus/, /ˈjuz/\nof\t/ˈəv/\n"));
const lookup={us,gb:new Map(),manual:{}};
us.set('a',['ə']);us.set('book',['bʊk']);
const get=(word,meaning='',example='')=>transcribe({word,meaning,example},lookup).phonetic;
assert.equal(get('am','是'),'美 /æm/');assert.equal(get('AM','上午'),'美 /ˌeɪˈem/');
assert.equal(get('IT','信息技术'),'美 /aɪ tiː/');assert.equal(get('US','美国'),'美 /juː es/');
assert.equal(get('read','阅读'),'美 /riːd/');assert.equal(get('read','读的过去式'),'美 /red/');
assert.equal(get('lead','引领'),'美 /liːd/');assert.equal(get('lead','铅'),'美 /led/');
assert.equal(get('wind','风'),'美 /wɪnd/');assert.equal(get('reading a book','正在读书'),'美 /ˈriːdɪŋ ə bʊk/');
assert.equal(get('turn right/left'),'美 /tɝn raɪt/；/tɝn lɛft/');
assert.equal(get('first (1st)'),'美 /fɝst/');
assert.equal(get('make use of'),'美 /meɪk juːs əv/');
assert.equal(get('used to'),'美 /juːst tu/');
assert.equal(get('father (dad)'),'美 /ˈfɑðɝ/；/dæd/');
assert.match(get('foot (feet)'),/复数 feet/);
assert.ok(transcribe({word:'not-in-the-source'},lookup).error,'unknown words stay unresolved rather than receiving invented transcriptions');
console.log('Phonetics supplement: meaning/tense selection, acronym casing, alternatives, ordinals, morphology and missing-source handling passed.');
