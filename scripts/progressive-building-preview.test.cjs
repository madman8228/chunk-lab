  await page.waitForFunction(()=>document.getElementById('feedback').textContent.includes('正在播放'));
  await page.getByRole('button',{name:'我理解了，继续'}).click();
  assert.equal(await page.getByRole('button',{name:'继续',exact:true}).isDisabled(),true);
  await page.getByRole('button',{name:'I need water some.',exact:true}).click();
  assert.match(await page.locator('#feedback').innerText(),/water 前面/);
  await page.getByRole('button',{name:'I need some water.',exact:true}).click();
  fs.mkdirSync('output/playwright/progressive-building',{recursive:true});
  await page.screenshot({path:'output/playwright/progressive-building/teaching.png',fullPage:true});
  await page.getByRole('button',{name:'继续',exact:true}).click();
  await page.getByRole('button',{name:'在句末加 please',exact:true}).click();
  await page.getByRole('button',{name:'继续',exact:true}).click();
  await page.getByRole('button',{name:'把 water 换成 food',exact:true}).click();
  await page.getByRole('button',{name:'继续',exact:true}).click();
  assert.equal((await page.locator('#task').innerText()).includes('I need some tea'),false);
  await page.getByRole('button',{name:'准备好自己说了'}).click();
  assert.equal(await page.locator('#chain').isVisible(),false);
  assert.equal(await page.locator('.reference').count(),0);
  await page.setViewportSize({width:360,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'output/playwright/progressive-building/independent-mobile.png',fullPage:true});
  await page.getByRole('textbox',{name:'输入英文表达'}).fill('Some tea, please.');
  await page.getByRole('button',{name:'提交表达',exact:true}).click();
  assert.match(await page.locator('#feedback').innerText(),/不是本课/);
  assert.equal(await page.getByRole('textbox').isDisabled(),true);
  await page.getByRole('button',{name:'换一个情境'}).click();
  await page.getByRole('button',{name:'需要提示',exact:true}).click();
