'use strict';
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Database = require('better-sqlite3');
const { createMembershipRepository } = require('./repository');
const { createEntitlementService } = require('./entitlement-service');
const { createTrialUsageMeter } = require('./trial-usage-meter');
const { createMembershipService } = require('./membership-service');
const { createMembershipCodeIssuer, normalizeCode } = require('./code-issuer');
const { createMembershipAdminService } = require('./admin-service');
const { createRedemptionService } = require('./redemption-service');
const { buildCodeCsv } = require('./csv-code-delivery');

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'chunklab-membership-regressions-'));
const db = new Database(path.join(dir, 'fixture.db'));
try {
  db.pragma('foreign_keys = ON');
  db.exec("CREATE TABLE users(id INTEGER PRIMARY KEY,username TEXT NOT NULL); INSERT INTO users VALUES(1,'one'),(2,'two'),(3,'three');");
  let time = Date.UTC(2026, 9, 14);
  const clock = { now: () => time };
  const repository = createMembershipRepository(db, clock);
  repository.saveSettings(1, { enabled: true, trialDays: 3, dailyLimitSeconds: 20 }, 1);
  const entitlements = createEntitlementService({ db, now: clock.now });
  const meter = createTrialUsageMeter({ db, repository, entitlements, now: clock.now });
  const membership = createMembershipService({ db, repository, entitlements, usageMeter: meter, now: clock.now });
  const session = meter.start(1, 'sentence', 'start_request_000001');
  const replay = meter.start(1, 'sentence', 'start_request_000001');
  assert.equal(replay.status, 200);
  assert.equal(replay.mode, 'trial');
  assert.equal(replay.sessionId, session.sessionId);
  assert.equal(meter.start(1, 'image-text', 'start_request_000001').code, 'IDEMPOTENCY_CONFLICT');
  assert.equal(membership.getStatus(1).trial.status, 'available', 'reserved final lease is still usable');
  assert.equal(membership.getStatus(1).trial.remainingSeconds, 20);
  time += 5000;
  const firstHeartbeat = meter.heartbeat(1, session.sessionId, 1);
  assert.equal(firstHeartbeat.status, 200);
  assert.equal(meter.heartbeat(1, session.sessionId, 1).leaseEndsAt, firstHeartbeat.leaseEndsAt);
  const windowBeforeRollback = db.prepare('SELECT * FROM user_trial_windows WHERE user_id=1').get();
  time -= 1000;
  assert.equal(meter.heartbeat(1, session.sessionId, 2).code, 'CLOCK_ERROR');
  assert.deepEqual(db.prepare('SELECT * FROM user_trial_windows WHERE user_id=1').get(), windowBeforeRollback);
  time = firstHeartbeat.leaseEndsAt;
  assert.equal(meter.heartbeat(1, session.sessionId, 1).code, 'SESSION_EXPIRED', 'replay cannot authorize an expired lease');
  assert.equal(meter.start(1, 'sentence', 'start_request_000002').code, 'TRIAL_DAILY_LIMIT');
  const paused = meter.start(2, 'image-text', 'start_request_000003');
  time += 3000;
  const pause = meter.heartbeat(2, paused.sessionId, 1, true);
  assert.equal(pause.status, 200);
  assert.equal(meter.heartbeat(2, paused.sessionId, 1, true).replay, true);
  assert.equal(meter.heartbeat(2, paused.sessionId, 1, false).code, 'IDEMPOTENCY_CONFLICT');
  assert.equal(db.prepare('SELECT reserved_ms FROM user_trial_windows WHERE user_id=2').get().reserved_ms, 0);

  const secret = crypto.randomBytes(32);
  const keyProvider = { current: () => ({ version: 'v1', secret }), get: v => v === 'v1' ? { version: v, secret } : null, versions: () => ['v1'] };
  const issuer = createMembershipCodeIssuer({ repository, keyProvider });
  const admin = createMembershipAdminService({ db, repository, issuer, now: clock.now });
  const issued = issuer.issue({ planKey: 'monthly', quantity: 1, redeemBy: time + 100000, requestId: 'issue_request_000001' }, 1);
  assert.ok(buildCodeCsv(issued, issued.codes).includes(new Date(issued.redeemBy).toISOString()), 'CSV includes the actual redemption deadline');
  admin.changeBatch({ batchId: issued.batchId, action: 'activate', baseRevision: 1, requestId: 'activate_request_000001' }, 1);
  const trial = meter.start(3, 'sentence', 'start_request_000004');
  time += 1000;
  const before = db.prepare('SELECT * FROM user_trial_windows WHERE user_id=3').get();
  const failingEntitlements = { ...entitlements, project() { throw new Error('injected projection failure'); } };
  const redemption = createRedemptionService({ db, repository, issuer, entitlements: failingEntitlements, trialMeter: meter, now: clock.now });
  assert.throws(() => redemption.redeem(3, issued.codes[0].code, 'redeem_request_000001', 'test-ip'), /injected/);
  assert.equal(db.prepare('SELECT status FROM redemption_codes WHERE code_id=?').get(issued.codes[0].codeId).status, 'unused');
  assert.equal(db.prepare('SELECT COUNT(*) AS count FROM user_entitlement_grants').get().count, 0);
  assert.equal(db.prepare('SELECT status FROM user_trial_sessions WHERE session_id=?').get(trial.sessionId).status, 'active');
  assert.deepEqual(db.prepare('SELECT * FROM user_trial_windows WHERE user_id=3').get(), before);
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM redemption_attempts WHERE account_key='3' AND succeeded=0").get().count, 1, 'failure rate state survives business rollback');
  assert.throws(() => normalizeCode('CL1-' + 'ſ'.repeat(32)), /格式/);
  console.log('membership replay, clock, final lease, pause, CSV, and transaction rollback regressions passed');
} finally {
  db.close();
  fs.rmSync(dir, { recursive: true, force: true });
}
