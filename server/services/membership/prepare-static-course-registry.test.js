'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { ContentRegistry } = require('./content-registry');
const { prepareStaticCourseRegistry } = require('./prepare-static-course-registry');
const { deckIdentity } = require('./assessment-content');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'chunklab-prepare-registry-'));
const appRoot = path.join(temp, 'app'), protectedRoot = path.join(temp, 'original'); fs.mkdirSync(appRoot); fs.mkdirSync(protectedRoot);
const content = { items: Array.from({ length: 12 }, (_, i) => ({ cid: 'c' + i, sentence: 'Original ' + i, hints: ['保留'], acceptedAnswers: ['alternative'], extraTeachingField: i })), authoring: { roles: [{ key: 'a', name: 'Role A' }] } };
fs.writeFileSync(path.join(protectedRoot, 'source.json'), JSON.stringify(content));
const unit = { unitId: 'unit', file: 'source.json', contentRef: { type: 'sentence-deck', id: 'old' }, itemIds: content.items.map(i => i.cid), assets: [] };
const course = { courseId: 'legacy', title: 'Original', contentType: 'sentence', defaultAccess: 'free', sourcePaths: ['/raw.js'], legacyDeckIds: ['old'], units: [{ ...unit, legacyLearningIdentity: { deckId: 'old', generationScope: 'course:old' } }] };
fs.writeFileSync(path.join(protectedRoot, 'registry.json'), JSON.stringify({ schemaVersion: 1, courses: [course, { ...course, courseId: 'ai-old', legacyDeckIds: [], units: [unit] }] }));
const originals = fs.readdirSync(protectedRoot).map(file => [file, crypto.createHash('sha256').update(fs.readFileSync(path.join(protectedRoot, file))).digest('hex')]);
const registry = new ContentRegistry({ appRoot, protectedRoot });
const output = path.join(temp, 'new-private');
const result = prepareStaticCourseRegistry({ registry, output }); assert.equal(result.activationReady, false); assert.equal(result.courseCount, 2);
const candidate = JSON.parse(fs.readFileSync(path.join(output, 'candidate.json')));
assert.equal(candidate.schemaVersion, 2); assert.equal(candidate.courses[0].units[0].recordIdentity.deckId, 'old');
assert.equal(candidate.courses[1].units[0].recordIdentity.deckId, deckIdentity('ai-old', 'unit'));
assert.equal(candidate.courses[1].units[0].recordIdentity.generationScope, 'course:ai-old');
assert.deepEqual(candidate.courses[0].units[0].fragments.flatMap(part => JSON.parse(fs.readFileSync(path.join(output, part.file))).items), content.items);
assert.deepEqual(JSON.parse(fs.readFileSync(path.join(output, candidate.courses[0].units[0].fragments[0].file))).context.authoring, content.authoring);
let reads=0;
const converted=new ContentRegistry({appRoot,protectedRoot:output,activeManifest:()=>{reads++;return {body:JSON.stringify(candidate)};}});
const loaded=converted.load('legacy','unit',1);
assert.equal(reads,1,'one content read uses one validated registry snapshot');
assert.deepEqual(loaded.payload.items,content.items.slice(1,10));
assert.equal(loaded.payload.recordIdentity.deckId,'old');
for (const [file, hash] of originals) assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(protectedRoot, file))).digest('hex'), hash);
assert.throws(() => prepareStaticCourseRegistry({ registry, output }), /OUTPUT_ALREADY_EXISTS/);
assert.throws(() => prepareStaticCourseRegistry({ registry, output: path.join(appRoot, 'public-candidate') }), /PUBLIC_OUTPUT_FORBIDDEN/);
assert.equal(fs.readdirSync(protectedRoot).length, originals.length, 'preparation never installs or changes original registry');
console.log('static registry preparation: v1-to-v2 additive artifact, original bytes, legacy/published identity, teaching context and exclusive output passed');
