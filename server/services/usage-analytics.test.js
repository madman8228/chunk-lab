'use strict';
const assert = require('node:assert/strict');
const Database = require('better-sqlite3');
const { initializeUsageSchema, createUsageAnalytics, dayOf, dayStart } = require('./usage-analytics');
const { createAdminOverview } = require('./admin-overview');
const db = new Database(':memory:');
db.pragma('foreign_keys=ON');
db.exec(`CREATE TABLE users(id INTEGER PRIMARY KEY,username TEXT,created_at TEXT);
  INSERT INTO users VALUES(1,'learner','2026-10-01'),(2,'word-only','2026-10-01'),(3,'__default__','2026-10-01');
  CREATE TABLE user_activity(user_id INTEGER,day TEXT,first_seen_at INTEGER,last_seen_at INTEGER,page_views INTEGER);
  CREATE TABLE user_events(user_id INTEGER,at INTEGER,data_json TEXT,deleted_at TEXT);
  CREATE TABLE user_entity_rows(user_id INTEGER,kind TEXT,deleted_at TEXT);
  CREATE TABLE vocabulary_study_events(user_id INTEGER,occurred_at INTEGER,resource_id TEXT);
  CREATE TABLE vocabulary_attempts(user_id INTEGER,occurred_at INTEGER);`);
initializeUsageSchema(db);
initializeUsageSchema(db);
let time = Date.parse('2026-10-14T23:59:55+08:00');
const usage = createUsageAnalytics({ db, now: () => time });
const pulse = (sequence, elapsedMs, sessionId = 'session-one-12345', user = 1) => usage.pulse(user, { sessionId, sequence, elapsedMs, kind: 'wordbook', resourceId: 'wordbook:test' });
assert.equal(pulse(1, 30000).creditedMs, 0, 'a new session cannot invent preceding study');
time += 10000;
assert.equal(pulse(2, 10000).creditedMs, 10000);
assert.deepEqual(usage.userTime(1).daily, [{ day: '2026-10-15', activeMs: 5000 }, { day: '2026-10-14', activeMs: 5000 }]);
assert.equal(pulse(2, 10000).creditedMs, 0, 'retries are idempotent');
assert.equal(pulse(1, 10000).creditedMs, 0, 'out of order pulses are ignored');
assert.equal(pulse(1, 0, 'session-two-12345').creditedMs, 0);
time += 10000;
assert.equal(pulse(3, 10000).creditedMs, 10000);
assert.equal(pulse(2, 10000, 'session-two-12345').creditedMs, 0, 'another tab/device cannot duplicate an interval');
pulse(1, 0, 'session-other-123', 2);
time += 10000;
assert.equal(pulse(2, 10000, 'session-other-123', 2).creditedMs, 10000, 'accounts are independent');
time += 3600000;
assert.equal(pulse(4, 30000).creditedMs, 30000, 'a long offline gap is bounded to one pulse');
assert.throws(() => pulse(5, 30001), /格式/);
assert.equal(usage.userTime(1).totalMs, 50000);
assert.equal(usage.userTime(2).totalMs, 10000);
db.prepare('INSERT INTO vocabulary_study_events VALUES(?,?,?)').run(2,time,'wordbook:test');
db.prepare('INSERT INTO vocabulary_attempts VALUES(?,?)').run(2,time);
db.prepare('INSERT INTO user_events VALUES(?,?,?,NULL)').run(1,time,JSON.stringify({kind:'answer',key:'deck#one'}));
db.prepare('INSERT INTO user_events VALUES(?,?,?,NULL)').run(3,time,JSON.stringify({kind:'answer',key:'deck#default'}));
db.prepare('INSERT INTO user_events VALUES(?,?,?,NULL)').run(1,dayStart('2026-10-09')-1,JSON.stringify({kind:'answer',key:'too-old'}));
db.prepare('INSERT INTO user_activity VALUES(?,?,?,?,?)').run(2,dayOf(time),time,time,1);
const overview = createAdminOverview({ db, admin: {}, shanghaiDay: dayOf, now: () => time }).adminOverview(7);
assert.equal(overview.range.startDay, '2026-10-09');
assert.equal(overview.daily.length, 7, 'calendar days are zero-filled');
assert.equal(overview.usage.answers, 3, 'sentence, wordbook and pilot events count once each');
assert.equal(overview.today.activeVisitors, 1);
assert.equal(overview.today.activeLearners, 2);
assert.equal(overview.today.activeMs, 55000);
assert.equal(overview.usage.activeMs, 60000);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM users').get().n, 3, 'original accounts remain intact');
db.close();
console.log('usage analytics: midnight split, account isolation, cross-device union, retries, bounded gaps, word learning and calendar ranges passed');
