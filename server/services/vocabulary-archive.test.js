'use strict';
const assert = require('node:assert/strict');
const Database = require('../node_modules/better-sqlite3');
const { createVocabularyArchive } = require('./vocabulary-archive');
const { registerLearningArchiveRoutes } = require('../routes/learning-archive');
const db = new Database(':memory:');
try {
  db.exec(`CREATE TABLE vocabulary_item_progress(user_id INTEGER,item_id TEXT,data_json TEXT);
    CREATE TABLE vocabulary_study_events(user_id INTEGER,event_id TEXT,item_id TEXT,resource_id TEXT,content_revision TEXT,data_json TEXT,occurred_at INTEGER);
    CREATE TABLE vocabulary_attempts(user_id INTEGER,event_id TEXT,word TEXT,independent INTEGER,occurred_at INTEGER);
    CREATE TABLE vocabulary_attempt_events(user_id INTEGER,attempt_id TEXT,item_id TEXT,resource_id TEXT,content_revision TEXT,data_json TEXT,occurred_at INTEGER);`);
  db.prepare('INSERT INTO vocabulary_item_progress VALUES(?,?,?)').run(1,'borrow-sense-1',JSON.stringify({dueAt:100,lastAt:10}));
  db.prepare('INSERT INTO vocabulary_study_events VALUES(?,?,?,?,?,?,?)').run(1,'same','borrow-sense-1','wordbook:a','v1','{"assisted":true}',200);
  db.prepare('INSERT INTO vocabulary_study_events VALUES(?,?,?,?,?,?,?)').run(1,'other','borrow-sense-1','wordbook:b','v1','{"assisted":true,"practiceType":"word-choice","inputMode":"choice"}',300);
  db.prepare('INSERT INTO vocabulary_study_events VALUES(?,?,?,?,?,?,?)').run(1,'same-book','borrow-sense-1','wordbook:a','v1','{"assisted":true}',250);
  db.prepare('INSERT INTO vocabulary_attempts VALUES(?,?,?,?,?)').run(1,'same','borrow',1,200);
  db.prepare('INSERT INTO vocabulary_attempts VALUES(?,?,?,?,?)').run(2,'private','secret',1,400);
  db.prepare('INSERT INTO vocabulary_attempt_events VALUES(?,?,?,?,?,?,?)').run(1,'wrong','borrow-sense-1','wordbook:a','v1',JSON.stringify({correct:false,answers:{text:'lend'},stepIndex:1,practiceType:'guided-expression',inputMode:'typing'}),400);
  db.prepare('INSERT INTO vocabulary_attempt_events VALUES(?,?,?,?,?,?,?)').run(2,'private','secret','wordbook:private','v1',JSON.stringify({correct:false}),500);
  const lookups=new Map(),content={book:(bookId,userId)=>{lookups.set(bookId,(lookups.get(bookId)||0)+1);if(userId!==1||bookId==='private')throw Object.assign(Error('unavailable'),{status:404});return {title:'同名成人课程'};},item:()=>null};
  const archive = createVocabularyArchive({db,content,now:()=>500});
  const before = db.prepare('SELECT total_changes() AS count').get().count;
  const summary = archive.summary(1);
  assert.equal(summary.domains[0].learnedItems,1,'same knowledge in two books is not doubled');
  assert.equal(summary.domains[0].events,3);
  assert.equal(summary.domains[0].dueItems,null,'global due dates cannot represent book- and practice-specific review status');
  assert.deepEqual(summary.domains[0].frequentErrors.map(row=>[row.itemId,row.wrongAnswers]),[['borrow-sense-1',1]],'word mistakes are ranked per course item');
  assert.equal(summary.domains[0].attemptedAnswers,1);assert.equal(summary.domains[0].incorrectAnswers,1);assert.equal(archive.attempts(1,{incorrect:'true'}).items[0].answers.text,'lend');assert.equal(archive.attempts(3).items.length,0);assert.equal(archive.attempts(1,{incorrect:'false'}).items.length,0);assert.throws(()=>archive.attempts(1,{incorrect:'other'}),/筛选/);
  assert.equal(summary.domains[1].learnedItems,1);
  assert.equal(summary.combinedUniqueItems,null);
  assert.equal(summary.domains[0].verifiedApplicationMastery,0);
  const page = archive.events(1,{limit:2});
  assert.equal(page.items.length,2);
  assert.equal(page.items[0].practiceType,'word-choice','archive preserves the actual saved exercise type');
  assert.equal(page.items[0].inputMode,'choice');
  assert.equal(page.nextOffset,2);
  const next = archive.events(1,{limit:2,offset:page.nextOffset});
  assert.equal(next.items.length,2);
  assert.equal(next.nextOffset,null);
  assert.equal([...page.items,...next.items].find(row=>row.source==='vocabulary-pilot').practiceType,null,'legacy events are not assigned invented exercise types');
  assert.equal(new Set([...page.items,...next.items].map(row=>row.id)).size,4);
  assert.equal([...page.items,...next.items].some(row=>row.itemId==='secret'),false);
  lookups.clear();const linked=archive.events(1,{limit:10}).items;
  assert.equal(linked.filter(row=>row.course?.title==='同名成人课程').length,3);
  assert.notEqual(linked.find(row=>row.resourceId==='wordbook:a').course.bookId,linked.find(row=>row.resourceId==='wordbook:b').course.bookId,'same-title courses retain distinct identities');
  assert.equal(lookups.get('a'),1,'course metadata is resolved once per distinct course per response');
  assert.deepEqual(archive.events(1,{limit:10}).items.find(row=>row.source==='vocabulary-pilot').course,null,'legacy pilot events have no invented course');
  assert.equal(archive.attempts(1).items[0].course.bookId,'a');
  assert.equal(archive.summary(3).domains[0].learnedItems,0);
  assert.deepEqual(archive.events(3).items,[]);
  for (const query of [{limit:101},{limit:0},{offset:-1},{offset:'bad'}]) assert.throws(()=>archive.events(1,query),/分页/);
  const routes=[]; const authenticate=()=>{};
  registerLearningArchiveRoutes({app:{get:(...args)=>routes.push(args)},auth:{authenticate},db});
  assert.equal(routes.length,6);
  assert.equal(routes.every(route=>route[1]===authenticate),true,'all archive reads require authentication');
  assert.equal(db.prepare('SELECT total_changes() AS count').get().count,before,'all projections are read-only');
  console.log('vocabulary archive: owner isolation, pagination, knowledge identity and read-only contract passed');
} finally { db.close(); }
