import assert from 'node:assert/strict';
import { AuthoringView } from './view.mjs';
const root = { innerHTML: '', dataset: {} };
const view = new AuthoringView({ root });
const snapshot = { sessionId:'isolated-feedback-test', stage:'preview', validatedDraft:{ title:'Test', items:[] }, validationReport:{} };
view.render(snapshot, { saving:true });
assert.match(root.innerHTML, /disabled>正在保存/);
assert.doesNotMatch(root.innerHTML, /data-action="save"/);
assert.equal(snapshot.stage, 'preview', 'visual feedback must not mutate persisted session');
view.render({ ...snapshot, stage:'saving' }, { saveDelayed:true });
assert.match(root.innerHTML, /等待保存确认/);
assert.doesNotMatch(root.innerHTML, /正在保存…/);
assert.doesNotMatch(root.innerHTML, /data-action="save"/);
view.render({ ...snapshot, stage:'saving' }, { synchronizationError:'SERVER_SEQ_ROLLBACK' });
assert.match(root.innerHTML, /保存受阻/);
assert.match(root.innerHTML, /数据版本不一致/);
assert.match(root.innerHTML, /data-action="export"/);
assert.doesNotMatch(root.innerHTML, /课程已保存到当前账号/);
view.render({ ...snapshot, stage:'saved' });
assert.match(root.innerHTML, /课程已保存到当前账号的课程库/);
view.render(snapshot, { error:'保存失败测试' });
assert.match(root.innerHTML, /issue-panel has-error[^>]*role="alert">保存失败测试/);
console.log('save feedback: waiting, success and nearby failure verified');
