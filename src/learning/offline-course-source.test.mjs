import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {OfflineCourseSource} from './offline-course-source.mjs';
import {CourseContentGateway} from './course-content-gateway.mjs';
const {createOfflineLicense}=createRequire(import.meta.url)('../../server/services/membership/offline-license.js');
const keys=crypto.generateKeyPairSync('ec',{namedCurve:'prime256v1',publicKeyEncoding:{type:'spki',format:'pem'},privateKeyEncoding:{type:'pkcs8',format:'pem'}});
const now=Date.now(),scope={accountId:'fixture',service:'test',courseId:'course',unitId:'unit',contentVersion:'v1'};
const identity={deckId:'fixture',generationScope:'course:course',resumeIdentity:'fixture'};
const batches=[0,1].map(cursor=>({cursor,items:[{cid:'sentence-'+cursor}],nextCursor:cursor===0?1:null,contentType:'sentence',recordIdentity:identity}));
const body=new TextEncoder().encode(JSON.stringify({version:1,courseId:'course',unitId:'unit',contentVersion:'v1',recordIdentity:identity,batches}));
const signer=createOfflineLicense({...keys,now:()=>now});const license=signer.issue({...scope,sha256:crypto.createHash('sha256').update(body).digest('hex')},{allowed:true,mode:'member',endsAt:now+1000});
let time=now,owner='fixture';const captureScope=()=>owner;
const source=new OfflineCourseSource({captureScope,now:()=>time,readPackage:async()=>({scope,body,license,publicKey:signer.publicJwk(),lastConfirmedTime:now})});
const gateway=new CourseContentGateway({captureScope,sources:{offline:source}});
assert.equal((await gateway.open({origin:'offline',courseId:'course',unitId:'unit'})).batch.items[0].cid,'sentence-0');
assert.ok(gateway.checkAdvance());assert.equal((await gateway.loadBatch(1)).items[0].cid,'sentence-1');
time=now+500;assert.ok(gateway.checkAdvance());
time=now+100;assert.equal(gateway.checkAdvance(),false,'clock rollback after a confirmed advance must pause learning');
await assert.rejects(gateway.loadBatch(1));
time=now+1000;assert.equal(gateway.checkAdvance(),false);await assert.rejects(gateway.loadBatch(1));
owner='other';assert.throws(()=>gateway.checkAdvance(),/SESSION_CHANGED/);
console.log('Offline source through actual gateway: start, cross-batch advance, expiry and account switch passed');
